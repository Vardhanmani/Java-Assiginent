public class DataTypesExample {
    public static void main(String[] args) {
        int age = 22;
        boolean isStudent = true;
        char grade = 'A';
        float percentage = 83.6f;     
        double temperature = 36.602;

        // Printing variable values to the console
        System.out.println("Integer value (int): " + age);
        System.out.println("Boolean value (boolean): " + isStudent);
        System.out.println("Character value (char): " + grade);
        System.out.println("Float value (float): " + percentage);
        System.out.println("Double value (double): " + temperature);
    }
}